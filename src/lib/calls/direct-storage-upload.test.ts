import { beforeEach, describe, expect, it, vi } from "vitest";

const { getSession } = vi.hoisted(() => ({ getSession: vi.fn() }));
vi.mock("@/lib/supabase/browser", () => ({
  createSupabaseBrowserClient: () => ({ auth: { getSession } }),
}));
vi.mock("@/lib/env/public", () => ({
  getPublicSupabaseConfig: () => ({
    supabaseUrl: "http://127.0.0.1:54321",
    publishableKey: "sb_publishable_local_test_key",
  }),
}));

import { uploadDirectToSupabaseStorage } from "./direct-storage-upload";

const objectPath = "20000000-0000-4000-8000-000000000001/30000000-0000-4000-8000-000000000001.mp3";

describe("direct authenticated Storage upload", () => {
  beforeEach(() => {
    getSession.mockReset().mockResolvedValue({
      data: { session: { access_token: "test-auth-session-token" } },
      error: null,
    });
  });

  it("sends bytes and the signed-in user's JWT directly to Supabase Storage with progress", async () => {
    const listeners = new Map<string, (event: ProgressEvent) => void>();
    let progressListener: ((event: ProgressEvent) => void) | undefined;
    const request = {
      upload: { addEventListener: vi.fn((_name: string, listener: (event: ProgressEvent) => void) => { progressListener = listener; }) },
      addEventListener: vi.fn((name: string, listener: (event: ProgressEvent) => void) => listeners.set(name, listener)),
      open: vi.fn(),
      setRequestHeader: vi.fn(),
      send: vi.fn((body: Document | XMLHttpRequestBodyInit | null) => {
        progressListener?.({ lengthComputable: true, loaded: 4_284, total: 4_284 } as ProgressEvent);
        listeners.get("load")?.({} as ProgressEvent);
        expect(body).toBe(file);
      }),
      status: 201,
      timeout: 0,
    };
    const file = new File([new Uint8Array(4_284)], "synthetic-tone.mp3", { type: "audio/mpeg" });
    vi.stubGlobal("XMLHttpRequest", vi.fn(function () { return request as unknown as XMLHttpRequest; }));
    const progress = vi.fn();

    await uploadDirectToSupabaseStorage(objectPath, file, progress);

    expect(request.open).toHaveBeenCalledWith(
      "POST",
      "http://127.0.0.1:54321/storage/v1/object/pestlaunch-call-audio/" + objectPath,
    );
    expect(request.setRequestHeader).toHaveBeenCalledWith("Authorization", "Bearer test-auth-session-token");
    expect(request.setRequestHeader).toHaveBeenCalledWith("apikey", "sb_publishable_local_test_key");
    expect(request.setRequestHeader).toHaveBeenCalledWith("Content-Type", "audio/mpeg");
    expect(request.setRequestHeader).toHaveBeenCalledWith("x-upsert", "false");
    expect(progress).toHaveBeenLastCalledWith(100);
  });

  it("refuses to send a Storage request without an authenticated session", async () => {
    getSession.mockResolvedValue({ data: { session: null }, error: null });
    const xhr = vi.fn();
    vi.stubGlobal("XMLHttpRequest", xhr);
    const file = new File([new Uint8Array([1])], "synthetic-tone.mp3", { type: "audio/mpeg" });

    await expect(uploadDirectToSupabaseStorage(objectPath, file, vi.fn())).rejects.toThrow("AUTH_REQUIRED");
    expect(xhr).not.toHaveBeenCalled();
  });

  it("rejects object paths that were not generated by the server", async () => {
    const xhr = vi.fn();
    vi.stubGlobal("XMLHttpRequest", xhr);
    const file = new File([new Uint8Array([1])], "synthetic-tone.mp3", { type: "audio/mpeg" });

    await expect(uploadDirectToSupabaseStorage("../other-workspace/object.mp3", file, vi.fn())).rejects.toThrow("INVALID_STORAGE_PATH");
    expect(xhr).not.toHaveBeenCalled();
  });
});
